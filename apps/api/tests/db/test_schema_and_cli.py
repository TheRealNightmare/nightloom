UserFactory = Callable[..., Coroutine[Any, Any, User]]


TABLES = ("users", "sessions", "audit_events", "cases", "case_members")
ENUM_TYPES = ("user_role", "case_legal_basis", "case_status", "case_member_role")


def table_names(connection: Connection) -> set[str]:
    return set(inspect(connection).get_table_names())


async def test_migration_downgrades_and_upgrades(infra: Infra) -> None:
    config = alembic_config()
    await infra.engine.dispose()  # no open connections while tables are dropped

    call_in_thread(lambda: command.downgrade(config, "0001_baseline"))
    async with infra.engine.connect() as conn:
        assert not set(TABLES) & await conn.run_sync(table_names)
        # The enum types are dropped too, or the next upgrade would fail.
        for enum in ENUM_TYPES:
            assert (
                await conn.scalar(
                    text("SELECT 1 FROM pg_type WHERE typname = :name"), {"name": enum}
                )
                is None
            )
        # So is the append-only trigger function.
        assert (
            await conn.scalar(
                text("SELECT 1 FROM pg_proc WHERE proname = 'audit_events_append_only'")
            )
            is None
        )

    call_in_thread(lambda: command.upgrade(config, "head"))
    async with infra.engine.connect() as conn:
        assert set(TABLES) <= await conn.run_sync(table_names)
        assert await conn.scalar(
            text("SELECT 1 FROM pg_trigger WHERE tgname = 'audit_events_append_only'")
        )


def user_columns(connection: Connection) -> dict[str, Any]:
    return {column["name"]: column for column in inspect(connection).get_columns("users")}


async def test_must_change_password_migration(infra: Infra, make_user: UserFactory) -> None:
    await make_user()  # an existing user keeps working across the migration
    config = alembic_config()
    await infra.engine.dispose()

    call_in_thread(lambda: command.downgrade(config, "0005_jobs"))
    async with infra.engine.connect() as conn:
        assert "must_change_password" not in await conn.run_sync(user_columns)

    call_in_thread(lambda: command.upgrade(config, "head"))
    async with infra.engine.connect() as conn:
        column = (await conn.run_sync(user_columns))["must_change_password"]
        assert column["nullable"] is False
        assert str(column["default"]) == "false"
        assert await conn.scalar(text("SELECT bool_or(must_change_password) FROM users")) is False


