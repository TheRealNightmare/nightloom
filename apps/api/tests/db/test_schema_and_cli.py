async def run_cli(*args: str, stdin: str) -> tuple[int, str, str]:
    env = {**os.environ, "NIGHTLOOM_DATABASE_URL": TEST_DATABASE_URL, "NIGHTLOOM_ENV": "test"}
    process = await asyncio.create_subprocess_exec(
        sys.executable,
        "-m",
        "nightloom_api.cli",
        *args,
        stdin=asyncio.subprocess.PIPE,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
        env=env,
    )
    out, err = await process.communicate(stdin.encode())
    assert process.returncode is not None
    return process.returncode, out.decode(), err.decode()


async def test_cli_end_to_end(infra: Infra) -> None:
    args = (
        "create-admin",
        "--email",
        "cli@example.org",
        "--display-name",
        "CLI",
        "--password-stdin",
    )

    code, out, err = await run_cli(*args, stdin=f"{PASSWORD}\n")
    assert (code, out.strip(), err) == (0, "Created admin cli@example.org.", "")

    code, out, err = await run_cli(*args, stdin=f"{PASSWORD}\n")
    assert code == 1
    assert err.strip() == "error: A user with this email already exists."
    assert PASSWORD not in out + err
