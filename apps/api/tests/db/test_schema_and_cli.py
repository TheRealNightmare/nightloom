async def test_create_admin(db_settings: Settings, infra: Infra) -> None:
    email = await cli.create_admin(
        db_settings, email=" Root@Example.org ", display_name="Root", password=PASSWORD
    )

    assert email == "root@example.org"
    async with infra.sessionmaker() as db:
        user = (await db.execute(select(User).where(User.email == email))).scalar_one()
    assert user.role == Role.ADMIN
    assert user.is_active is True
    assert user.display_name == "Root"
    assert passwords.verify_password(PASSWORD, user.password_hash)[0] is True
    # The CLI's admin chose their own password: no forced change.
    assert user.must_change_password is False


